from __future__ import annotations

import json
from math import ceil, log2
from pathlib import Path


def _integer_code_bits(value: int) -> int:
    """Small monotone proxy for a self-delimiting non-negative integer code."""
    if value <= 0:
        return 1
    width = value.bit_length()
    return 2 * width + 1


def chain_case(length: int) -> dict[str, float | int]:
    """Compare a flat chain program with a factorized counter transition.

    An exact machine that may be at any one of length + 1 positions needs at
    least ceil(log2(length + 1)) active bits. A flat ground-rule program stores
    every edge separately. A factorized program stores one increment schema and
    the endpoint. Both still require length dependent transitions to traverse
    the chain; program compression does not erase unavoidable sequential work.
    """
    if length < 1:
        raise ValueError("length must be positive")

    state_bits = max(1, ceil(log2(length + 1)))
    opcode_bits = 3
    flat_rule_bits = length * (opcode_bits + 2 * state_bits)
    factorized_program_bits = 24 + _integer_code_bits(length)

    return {
        "length": length,
        "state_lower_bound_bits": state_bits,
        "flat_ground_program_bits": flat_rule_bits,
        "factorized_program_bits": factorized_program_bits,
        "factorized_runtime_state_bits": state_bits,
        "required_steps": length,
        "program_compression_ratio": flat_rule_bits / factorized_program_bits,
    }


def parity_case(input_bits: int) -> dict[str, float | int]:
    """Contrast an arbitrary Boolean map with the structured parity function.

    A completely arbitrary Boolean mapping on input_bits inputs needs 2^n output
    bits in the worst case. Parity is generated by a constant update rule and a
    single active state bit, but exact evaluation still has to read every input
    bit. This separates description complexity, working state, and read cost.
    """
    if input_bits < 1:
        raise ValueError("input_bits must be positive")

    arbitrary_map_bits = 1 << input_bits
    parity_program_bits = 16 + _integer_code_bits(input_bits)

    return {
        "input_bits": input_bits,
        "arbitrary_boolean_map_lower_bits": arbitrary_map_bits,
        "parity_program_bits": parity_program_bits,
        "parity_runtime_state_bits": 1,
        "required_input_reads": input_bits,
        "description_compression_ratio": arbitrary_map_bits / parity_program_bits,
    }


def repeated_query_case(length: int, queries: int) -> dict[str, int]:
    """Show why the optimal memory/index depends on the deployment workload.

    The proxy counts stored bits plus bits touched by repeated endpoint
    reachability queries on a chain. On-demand traversal avoids cache storage but
    repeatedly reads every edge. A one-query memo stores only the fact actually
    reused. A full transitive closure spends quadratic static bits for generic
    constant-time reachability. This is an accounting illustration, not a claim
    about a hardware-specific latency model.
    """
    if length < 1 or queries < 1:
        raise ValueError("length and queries must be positive")

    node_bits = max(1, ceil(log2(length + 1)))
    edge_record_bits = 2 * node_bits
    edge_store_bits = length * edge_record_bits

    on_demand_total = edge_store_bits + queries * length * edge_record_bits

    memo_static_bits = edge_store_bits + 1
    memo_read_bits = length * edge_record_bits + max(0, queries - 1)
    memo_total = memo_static_bits + memo_read_bits

    closure_static_bits = edge_store_bits + (length + 1) * length // 2
    closure_total = closure_static_bits + queries

    return {
        "length": length,
        "queries": queries,
        "edge_store_bits": edge_store_bits,
        "on_demand_total_bit_accesses": on_demand_total,
        "single_query_memo_total_bit_accesses": memo_total,
        "full_closure_total_bit_accesses": closure_total,
    }


def run() -> dict[str, object]:
    chain_lengths = [8, 16, 32, 64, 128, 256]
    parity_widths = [8, 12, 16, 20]
    repeated_queries = [1, 4, 16, 100]

    return {
        "chain": [chain_case(length) for length in chain_lengths],
        "parity": [parity_case(width) for width in parity_widths],
        "repeated_query": [
            repeated_query_case(64, count) for count in repeated_queries
        ],
        "interpretation": {
            "structured_programs": "short generative laws can avoid flat table growth",
            "unstructured_information": "arbitrary mappings retain exponential description lower bounds",
            "working_state": "factorized chain state meets the log2(number of positions) lower bound",
            "read_cost": "parity still reads every independent input bit",
            "workload_specificity": "memoization beats generic closure when one query repeats",
        },
    }


def render_markdown(payload: dict[str, object]) -> str:
    lines = [
        "# Phase 6a results: scaling and lower-bound audit",
        "",
        "This audit separates static program bits, active state bits, evidence reads,",
        "and unavoidable sequential work. It does not claim that universality alone",
        "produces an efficient intelligent system.",
        "",
        "## Chain: flat ground rules versus a factorized transition",
        "",
        "| length | state lower bound | flat program bits | factorized bits | required steps | compression |",
        "|---:|---:|---:|---:|---:|---:|",
    ]
    for row in payload["chain"]:
        lines.append(
            f"| {row['length']} | {row['state_lower_bound_bits']} | "
            f"{row['flat_ground_program_bits']} | {row['factorized_program_bits']} | "
            f"{row['required_steps']} | {row['program_compression_ratio']:.2f}x |"
        )

    lines.extend(
        [
            "",
            "The factorized machine reaches the exact active-state lower bound, while",
            "the flat ground program grows with every edge. The traversal still needs",
            "one dependent step per edge: compression does not make an inherently",
            "sequential computation constant-time.",
            "",
            "## Boolean functions: arbitrary table versus parity",
            "",
            "| input bits | arbitrary-map lower bits | parity program bits | active bits | required reads | compression |",
            "|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for row in payload["parity"]:
        lines.append(
            f"| {row['input_bits']} | {row['arbitrary_boolean_map_lower_bits']:,} | "
            f"{row['parity_program_bits']} | {row['parity_runtime_state_bits']} | "
            f"{row['required_input_reads']} | {row['description_compression_ratio']:.2f}x |"
        )

    lines.extend(
        [
            "",
            "Parity has a short algorithm and one-bit state, but every independent input",
            "bit must still be observed. An arbitrary mapping has no assumed structure and",
            "retains its table-sized information lower bound.",
            "",
            "## Repeated reachability query: workload-specific storage",
            "",
            "| queries | on demand | memo one query | full closure |",
            "|---:|---:|---:|---:|",
        ]
    )
    for row in payload["repeated_query"]:
        lines.append(
            f"| {row['queries']} | {row['on_demand_total_bit_accesses']:,} | "
            f"{row['single_query_memo_total_bit_accesses']:,} | "
            f"{row['full_closure_total_bit_accesses']:,} |"
        )

    lines.extend(
        [
            "",
            "The best representation depends on the deployment distribution. A universal",
            "full closure is wasteful when one endpoint query repeats; a single verified",
            "memo is smaller. With a different query distribution, the crossover changes.",
            "",
            "## Consequence for open-ended intelligence",
            "",
            "The scalable target is not one fixed table. It is a compiler that detects",
            "reusable structure, keeps active state near distinguishability lower bounds,",
            "reads only evidence that can affect the result, and specializes storage and",
            "indexes to the measured workload. Truly unstructured knowledge must still be",
            "stored or reacquired, and irreducibly dependent reasoning steps must still run.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    payload = run()
    output = Path("results")
    output.mkdir(parents=True, exist_ok=True)
    (output / "phase6a.json").write_text(
        json.dumps(payload, indent=2) + "\n", encoding="utf-8"
    )
    (output / "phase6a.md").write_text(render_markdown(payload), encoding="utf-8")
    print(json.dumps(payload, indent=2))


if __name__ == "__main__":
    main()
